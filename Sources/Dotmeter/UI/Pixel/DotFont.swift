        "↑": make("..#.. .###. #.#.# ..#.. ..#.. ..#.. ..#.."),
        "@": make(".###. #...# #.### #.#.# #.### #.... .###."),
        "*": make("..... #.#.# .###. ##### .###. #.#.# ....."),
        "°": make(".##.. #..#. #..#. .##.. ..... ..... ....."),
    ]
}
