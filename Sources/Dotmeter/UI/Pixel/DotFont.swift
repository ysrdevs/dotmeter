import Foundation

/// The letters of the displays: five dots wide, seven tall.
enum DotFont {
    static let height = 7
    static let width = 5

    /// The rows of a character, top to bottom, as bits: the leftmost dot is the highest of five bits.
    static func rows(_ character: Character) -> [UInt8] {
        glyphs[character] ?? glyphs[Character(String(character).uppercased())] ?? blank
    }

    /// How many dots wide `text` is, with one empty column between characters.
    static func columns(_ text: String) -> Int {
        max(text.count * (width + 1) - 1, 0)
    }

    private static let blank = [UInt8](repeating: 0, count: 7)

    private static func make(_ lines: String) -> [UInt8] {
        lines.split(separator: " ").map { line in
            line.reduce(UInt8(0)) { ($0 << 1) | ($1 == "#" ? 1 : 0) }
        }
    }

    private static let glyphs: [Character: [UInt8]] = [
        " ": blank,
        "A": make(".###. #...# #...# ##### #...# #...# #...#"),
        "B": make("####. #...# #...# ####. #...# #...# ####."),
        "C": make(".###. #...# #.... #.... #.... #...# .###."),
        "D": make("####. #...# #...# #...# #...# #...# ####."),
        "E": make("##### #.... #.... ####. #.... #.... #####"),
        "F": make("##### #.... #.... ####. #.... #.... #...."),
        "G": make(".###. #...# #.... #.### #...# #...# .###."),
        "H": make("#...# #...# #...# ##### #...# #...# #...#"),
        "I": make(".###. ..#.. ..#.. ..#.. ..#.. ..#.. .###."),
        "J": make("..### ...#. ...#. ...#. ...#. #..#. .##.."),
        "K": make("#...# #..#. #.#.. ##... #.#.. #..#. #...#"),
        "L": make("#.... #.... #.... #.... #.... #.... #####"),
        "M": make("#...# ##.## #.#.# #.#.# #...# #...# #...#"),
        "N": make("#...# #...# ##..# #.#.# #..## #...# #...#"),
        "O": make(".###. #...# #...# #...# #...# #...# .###."),
        "P": make("####. #...# #...# ####. #.... #.... #...."),
        "Q": make(".###. #...# #...# #...# #.#.# #..#. .##.#"),
        "R": make("####. #...# #...# ####. #.#.. #..#. #...#"),
        "S": make(".#### #.... #.... .###. ....# ....# ####."),
        "T": make("##### ..#.. ..#.. ..#.. ..#.. ..#.. ..#.."),
        "U": make("#...# #...# #...# #...# #...# #...# .###."),
        "V": make("#...# #...# #...# #...# #...# .#.#. ..#.."),
        "W": make("#...# #...# #...# #.#.# #.#.# #.#.# .#.#."),
        "X": make("#...# #...# .#.#. ..#.. .#.#. #...# #...#"),
        "Y": make("#...# #...# .#.#. ..#.. ..#.. ..#.. ..#.."),
        "Z": make("##### ....# ...#. ..#.. .#... #.... #####"),
        "0": make(".###. #...# #..## #.#.# ##..# #...# .###."),
        "1": make("..#.. .##.. ..#.. ..#.. ..#.. ..#.. .###."),
        "2": make(".###. #...# ....# ...#. ..#.. .#... #####"),
        "3": make("##### ...#. ..#.. ...#. ....# #...# .###."),
        "4": make("...#. ..##. .#.#. #..#. ##### ...#. ...#."),
        "5": make("##### #.... ####. ....# ....# #...# .###."),
        "6": make("..##. .#... #.... ####. #...# #...# .###."),
        "7": make("##### ....# ...#. ..#.. .#... .#... .#..."),
        "8": make(".###. #...# #...# .###. #...# #...# .###."),
        "9": make(".###. #...# #...# .#### ....# ...#. .##.."),
        ".": make("..... ..... ..... ..... ..... .##.. .##.."),
        ",": make("..... ..... ..... ..... .##.. ..#.. .#..."),
        ":": make("..... .##.. .##.. ..... .##.. .##.. ....."),
        "-": make("..... ..... ..... ##### ..... ..... ....."),
        "+": make("..... ..#.. ..#.. ##### ..#.. ..#.. ....."),
        "=": make("..... ..... ##### ..... ##### ..... ....."),
        "%": make("##... ##..# ...#. ..#.. .#... #..## ...##"),
        "/": make("..... ....# ...#. ..#.. .#... #.... ....."),
        "!": make("..#.. ..#.. ..#.. ..#.. ..#.. ..... ..#.."),
        "?": make(".###. #...# ....# ...#. ..#.. ..... ..#.."),
        "'": make("..#.. ..#.. .#... ..... ..... ..... ....."),
        "\"": make(".#.#. .#.#. .#.#. ..... ..... ..... ....."),
        "(": make("...#. ..#.. .#... .#... .#... ..#.. ...#."),
        ")": make(".#... ..#.. ...#. ...#. ...#. ..#.. .#..."),
        "&": make(".##.. #..#. #.#.. .#... #.#.# #..#. .##.#"),
        "#": make(".#.#. .#.#. ##### .#.#. ##### .#.#. .#.#."),
        "_": make("..... ..... ..... ..... ..... ..... #####"),
        "<": make("...#. ..#.. .#... #.... .#... ..#.. ...#."),
        ">": make(".#... ..#.. ...#. ....# ...#. ..#.. .#..."),
        "×": make("..... #...# .#.#. ..#.. .#.#. #...# ....."),
